def save_csv(records, path, columns):
    df = pd.DataFrame(records)

    if df.empty:
        df = pd.DataFrame(columns=columns)
    else:
        for c in columns:
            if c not in df.columns:
                df[c] = None
        df = df[columns]

    if "time" in df.columns and not df.empty:
        df["time"] = pd.to_datetime(df["time"]).dt.strftime("%Y-%m-%d %H:%M:%S")

    try:
        df.to_csv(path, index=False)
    except PermissionError:
        alt_path = path.replace(".csv", "_new.csv")
        df.to_csv(alt_path, index=False)

def fmt_id(raw_id):
    return str(raw_id).strip().ljust(2)

def solve_case():
    """
    Try several solve methods.
    Returns:
        solved (bool), solve_mode (str)
    """
    try:
        ierr = psspy.fnsl([1, 0, 0, 1, 1, 0, 99, 0])   # flat-start NR
        if ierr == 0 and psspy.solved() == 0:
            return True, "flat_start_nr"
    except:
        pass

    try:
        ierr = psspy.fnsl([0, 0, 0, 1, 1, 0, 99, 0])   # normal NR
        if ierr == 0 and psspy.solved() == 0:
            return True, "normal_nr"
    except:
        pass

    try:
        ierr = psspy.mslv()                            # fallback
        if ierr == 0 and psspy.solved() == 0:
            return True, "mslv"
    except:
        pass

    try:
        ierr = psspy.fnsl([0, 0, 0, 1, 1, 1, 99, 0])  # final retry
        if ierr == 0 and psspy.solved() == 0:
            return True, "nr_after_mslv"
    except:
        pass

    return False, "failed"

def machine_snapshot():
    """
    Snapshot all machine PGEN values.
    Returns dict like: {"12345_1": pgen, ...}
    """
    ierr1, bus = psspy.amachint(-1, 4, "NUMBER")
    ierr2, mid = psspy.amachchar(-1, 4, "ID")
    ierr3, pgen = psspy.amachreal(-1, 4, "PGEN")

    snap = {}
    if ierr1 == 0 and ierr2 == 0 and ierr3 == 0:
        for b, i, p in zip(bus[0], mid[0], pgen[0]):
            snap["{}_{}".format(b, i.strip())] = p
    return snap

def get_machine_name_map():
    out = {}
    try:
        gm = pd.read_csv(GEN_MAP)
        needed = {"bus", "id", "asset_group"}
        if needed.issubset(set(gm.columns)):
            for _, r in gm.iterrows():
                key = "{}_{}".format(int(r["bus"]), str(r["id"]).strip())
                out[key] = str(r["asset_group"]).strip()
    except:
        pass
    return out

