def mute_psse_output():
    """
    Disable PSSE console/screen output.
    ISLCT=6 -> no output device
    """
    psspy.report_output(6, "", [])
    psspy.progress_output(6, "", [])
    psspy.alert_output(6, "", [])
    psspy.prompt_output(6, "", [])

def route_psse_output_to_files(logs):
    """
    Send PSSE output to text files instead of console.
    ISLCT=2 -> output to file
    """
    psspy.report_output(2, logs["report"], [0, 0])
    psspy.progress_output(2, logs["progress"], [0, 0])
    psspy.alert_output(2, logs["alert"], [0, 0])
    psspy.prompt_output(2, logs["prompt"], [0, 0])

