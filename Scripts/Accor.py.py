# 8. ACCOR RUNNER
# =========================================================
def run_accor(t):
    """
    Build DFAX and run old ACCOR with text logs saved to file,
    while keeping PSSE console muted.
    Returns:
        success (bool), stage (str), ierr_code (int), logs (dict), dfax_ierr (int)
    """
    logs = build_log_paths(t)

    # Start routing PSSE output to files before DFAX/ACCOR
    # so console remains silent and text logs are preserved.
    start_psse_logging(logs)
    try:
        ierr_dfax = psspy.dfax_2([1, 1, 0], SUB_FILE, MON_FILE, CON_FILE, DFX_FILE)
        if ierr_dfax != 0:
            return False, "dfax_failed", ierr_dfax, logs, ierr_dfax

        ierr_accor = psspy.accor(ACCOR_OPTIONS, ACCOR_VALUES, ACCOR_LABELS, DFX_FILE)
        if ierr_accor != 0:
            return False, "accor_failed", ierr_accor, logs, ierr_dfax

    finally:
        stop_psse_logging()

    return True, "accor_ok", 0, logs, ierr_dfax

