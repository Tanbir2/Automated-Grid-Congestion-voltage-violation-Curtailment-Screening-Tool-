def get_metrics():
    thermal = []
    voltage = []
    max_loading = 0.0

    ierr1, data = psspy.abrnreal(-1, 0, 0, 1, 1, ["P", "Q", "RATEA"])
    ierr2, ids = psspy.abrnchar(-1, 0, 0, 1, 1, ["ID"])
    ierr3, buses = psspy.abrnint(-1, 0, 0, 1, 1, ["FROMNUMBER", "TONUMBER"])

    if ierr1 == 0 and ierr2 == 0 and ierr3 == 0:
        for fb, tb, ck, p, q, rate in zip(
            buses[0], buses[1], ids[0], data[0], data[1], data[2]
        ):
            mva = math.sqrt(p**2 + q**2)
            pct = (mva / rate) * 100.0 if rate > 0 else 0.0
            max_loading = max(max_loading, pct)

            if pct > THERMAL_LIMIT:
                thermal.append({
                    "branch": "{}-{}".format(fb, tb),
                    "ckt": ck.strip(),
                    "pct": round(pct, 2)
                })

    ierr4, b = psspy.abusint(-1, 2, "NUMBER")
    ierr5, v = psspy.abusreal(-1, 2, "PU")

    if ierr4 == 0 and ierr5 == 0:
        for bus, pu in zip(b[0], v[0]):
            if pu < V_MIN or pu > V_MAX:
                voltage.append({
                    "bus": bus,
                    "pu": round(pu, 4)
                })

    return max_loading, thermal, voltage

