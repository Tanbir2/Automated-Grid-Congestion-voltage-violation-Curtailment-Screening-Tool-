# 6. APPLY DISPATCH
# =========================================================
def apply_dispatch(t, ld, gd, gm):
    # -------------------------
    # LOAD
    # -------------------------
    hr_ld = ld[ld["datetime"] == t]
    for _, r in hr_ld.iterrows():
        psspy.load_chng_5(
            int(r["bus"]),
            fmt_id(r["id"]),
            realar1=float(r["p_mw"]),
            realar2=float(r["q_mvar"])
        )

    # -------------------------
    # GENERATION
    # simple equal-share logic
    # -------------------------
    hr_gn = gd[gd["datetime"] == t]
    for _, r in hr_gn.iterrows():
        mw = float(r["mw"])
        if mw <= 0.01:
            continue

        asset = str(r["asset_group"]).upper().strip()
        units = gm[gm["asset_group"] == asset]

        if not units.empty:
            share = mw / len(units)
            for _, u in units.iterrows():
                psspy.machine_chng_2(
                    int(u["bus"]),
                    fmt_id(u["id"]),
                    realar1=share
                )

